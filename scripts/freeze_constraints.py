"""Write the pinned dependency files from the tested environment:

  docker/constraints.txt   every package the-relay[redis] needs at run time (the image)
  requirements.txt         the same pins, for `pip install -r requirements.txt`
  requirements-dev.txt     requirements.txt plus the test and lint tools (the dev extra)

  python scripts/freeze_constraints.py

The Docker image installs with these constraints, so it runs the versions the test suite
ran with. That also keeps the tracked data/papers/manifest.json and
data/retrieval_manifest.json byte-identical when a container builds the indexes (both record
library versions and content digests). Re-run after upgrading a dependency.
"""

from __future__ import annotations

import importlib.metadata as metadata
import re
import sys
from pathlib import Path

ROOT_PACKAGE = "the-relay"
EXTRAS = {"redis"}
OUT = Path("docker/constraints.txt")
REQUIREMENTS = Path("requirements.txt")
REQUIREMENTS_DEV = Path("requirements-dev.txt")
DEV_EXTRAS = EXTRAS | {"dev"}
_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*")
_EXTRAS = re.compile(r"\[([^\]]+)\]")
_LINUX_ONLY_MARKERS = ("sys_platform == \"win32\"", "platform_system == \"Windows\"")


def _canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _requirements(dist: metadata.Distribution,
                  extras: set[str]) -> list[tuple[str, set[str]]]:
    """The (name, extras) this distribution needs with ``extras`` selected; a dependency's
    own extras (``fakeredis[lua]``) are followed too."""
    names: list[tuple[str, set[str]]] = []
    for requirement in dist.requires or []:
        spec, _, marker = requirement.partition(";")
        marker = marker.strip()
        if "extra ==" in marker:
            wanted = re.findall(r"extra == ['\"]([^'\"]+)['\"]", marker)
            if not set(wanted) & extras:
                continue
        elif any(windows in marker for windows in _LINUX_ONLY_MARKERS):
            continue  # the image is Linux
        match = _NAME.match(spec.strip())
        if match:
            wanted_extras = _EXTRAS.search(spec)
            names.append((match.group(0), {e.strip() for e in wanted_extras.group(1).split(",")}
                          if wanted_extras else set()))
    return names


def closure(extras: set[str] = EXTRAS) -> dict[str, str]:
    pinned: dict[str, str] = {}
    pending = _requirements(metadata.distribution(ROOT_PACKAGE), extras)
    followed: set[tuple[str, str]] = set()  # (package, extra or "") already expanded
    while pending:
        raw, wanted = pending.pop()
        name = _canonical(raw)
        todo = {e for e in ({""} | wanted) if (name, e) not in followed}
        if not todo:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue  # an optional dependency for another platform
        pinned[name] = dist.version
        followed.update((name, e) for e in todo)
        pending.extend(_requirements(dist, todo - {""}) if todo - {""} else [])
        if "" in todo:
            pending.extend(_requirements(dist, set()))
    return pinned


def _write(path: Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    pinned = closure()
    python = f"Python {sys.version_info.major}.{sys.version_info.minor}"
    pins = [f"{name}=={version}" for name, version in sorted(pinned.items())]
    _write(OUT, ["# Generated by scripts/freeze_constraints.py from the tested environment",
                 f"# ({python}). Do not edit.", *pins])
    _write(REQUIREMENTS, [
        "# The Relay's run-time dependencies, pinned to the versions the test suite ran with",
        f"# ({python}). Generated by scripts/freeze_constraints.py; do not edit by hand.",
        "#",
        "#   pip install -r requirements.txt",
        "#   pip install --no-deps -e .        # the relay package and its `relay` command",
        "#",
        "# The ranges the package accepts are in pyproject.toml. Redis is included for the",
        "# optional multi-worker state backend; one process does not use it.",
        *pins])
    dev = closure(DEV_EXTRAS)
    dev_only = [f"{name}=={version}" for name, version in sorted(dev.items())
                if name not in pinned]
    _write(REQUIREMENTS_DEV, [
        "# Tests and lint, on top of the run-time pins. Generated by",
        "# scripts/freeze_constraints.py; do not edit by hand.",
        "#",
        "#   pip install -r requirements-dev.txt && pip install --no-deps -e .",
        "-r requirements.txt", *dev_only])
    print(f"{OUT} and {REQUIREMENTS}: {len(pinned)} packages; "
          f"{REQUIREMENTS_DEV}: {len(dev_only)} more")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
